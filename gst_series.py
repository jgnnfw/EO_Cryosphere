"""
Simplified glacier surface temperature (GST) time series from Landsat 8/9 (2015-present).
Based on Ren et al. 2024 (RSE 305, 114076): altitudinal area-weighting in 50 m bins,
outlier filters, half-month compositing, ablation-season (Jun-Sep) trend.

Requires:

>>> pip install earthengine-api geemap pandas numpy scipy matplotlib

Fully generated by Claude.
"""
import ee
import geemap
import matplotlib
from matplotlib import figure
import numpy as np
import pandas as pd
from scipy import stats
import os

# --------------- module specific config --------------------------------
BIN_M = 50  # elevation bin height (paper: 50 m)
MIN_BIN_CLEAR = 0.10  # drop bins with <10 % clear pixels (paper)
MIN_ZONE_COVER = 0.30  # min. valid area share per zone and half-month
MIN_HM_PER_SEASON = 3  # min. half-months (of 8) per ablation season
ABLATION_MONTHS = [6, 7, 8, 9]  # Jun-Sep (paper)
MAX_ST_UNC_K = 5.0  # drop pixels with ST_QA uncertainty > 5 K
N_ZONES = 3  # elevation zones with equal glacier area


# ----------- glacier mask and DEM ------------------------------------
def get_glacier_mask(roi: ee.Geometry) -> tuple[ee.Image, str]:
    """Uses public GLIMS outlines if present in the ROI, else the polygon ROI itself.
    :param roi: given region of interest in which the glacier lies, as list[[lon, lat], ...]
    :return: ee.Image as constant 1 on glacer area defined above and a status string which outlines were used.
    """
    try:
        g = ee.FeatureCollection("GLIMS/current").filterBounds(roi)
        if g.size().getInfo() > 0:
            return ee.Image().byte().paint(g, 1).selfMask(), "GLIMS/current outlines"
    except Exception as exc:  # asset missing / no access
        print("GLIMS not usable:", exc)
    return ee.Image.constant(1).clip(roi).selfMask(), "ROI polygon (no outlines found)"


# --------------- Landsat 8/9 L2 ----------------------------------------
def _prep(img: ee.Image | ee.Element) -> ee.Image | ee.Element: # dont know what it actually outputs
    img = ee.Image(img)
    qa = img.select("QA_PIXEL")
    clear = qa.bitwiseAnd(0b11110).eq(0)
    st_raw = img.select("ST_B10")
    unc = img.select("ST_QA").multiply(0.01)  # K
    mask = clear.And(unc.lt(MAX_ST_UNC_K)).And(st_raw.gt(0))
    st = st_raw.multiply(0.00341802).add(149.0).subtract(273.15).rename("ST") # some conversion to °C
    out = st.addBands(unc.rename("UNC")).updateMask(mask)
    return out.copyProperties(img, ["system:time_start", "system:index", "SPACECRAFT_ID"])


def _per_scene(img, bin_img: ee.Image, glacier_mask: ee.Image, roi: ee.Geometry) -> ee.FeatureCollection:
    """Per elevation bin: sum of valid ST, count of valid pixels, count of all glacier pixels."""
    img = ee.Image(img)
    st = _prep(img)
    st = ee.Image(st) # was element not image
    stack = ee.Image.cat([
        st.select("ST").unmask(0).rename("stsum"),
        st.select("UNC").unmask(0).rename("uncsum"),
        st.select("ST").mask().unmask(0).toFloat().rename("valid"),
        ee.Image.constant(1).rename("one"),
        bin_img.toFloat(),
    ]).updateMask(glacier_mask)
    reducer = ee.Reducer.sum().repeat(4).group(groupField=4, groupName="bin")
    res = stack.reduceRegion(reducer, roi, scale=30, maxPixels=1e9, tileScale=4)

    def to_feat(g) -> ee.Feature:
        g = ee.Dictionary(g)
        s = ee.List(g.get("sum"))
        return ee.Feature(None, {
            "bin": g.get("bin"), "stsum": s.get(0), "uncsum": s.get(1),
            "valid": s.get(2), "n": s.get(3),
            "time": img.get("system:time_start"), "scene": img.get("system:index"),
            "sensor": img.get("SPACECRAFT_ID"),
        })

    return ee.FeatureCollection(ee.List(res.get("groups")).map(to_feat))


def _landsat(roi: ee.Geometry, start: str, end: str):
    cols = [ee.ImageCollection(c).filterBounds(roi).filterDate(start, end)
            for c in ("LANDSAT/LC08/C02/T1_L2", "LANDSAT/LC09/C02/T1_L2")]
    return cols[0].merge(cols[1])


def download(bin_img: ee.Image | ee.Element, glacier_mask: ee.Image, roi: ee.Geometry, start: str, end: str) -> pd.DataFrame:
    rows = []
    for year in range(int(start[:4]), int(end[:4]) + 1):
        y0, y1 = f"{year}-01-01", f"{year + 1}-01-01"
        col = _landsat(roi, start=max(y0, start), end=min(y1, end))
        fc = col.map(lambda img: _per_scene(img, bin_img=bin_img, glacier_mask=glacier_mask, roi=roi)).flatten()
        feats = fc.getInfo()["features"]
        rows += [f["properties"] for f in feats]
        print(year, "scenes x bins:", len(feats))

    df = pd.DataFrame(rows)
    df["time"] = pd.to_datetime(df["time"], unit="ms")

    return df


# ---------------- processing -------------------------------------------
def _half_month(t):
    return (t.dt.month - 1) * 2 + (t.dt.day > 15).astype(int)  # 0..23


def process(df: pd.DataFrame) -> pd.DataFrame:

    df = df[df["valid"] > 0].copy()
    df["st"] = df["stsum"] / df["valid"]
    df["unc"] = df["uncsum"] / df["valid"]
    df["clear_frac"] = df["valid"] / df["n"]
    df = df[df["clear_frac"] >= MIN_BIN_CLEAR]  # paper filter 1

    # paper filter 2: spike vs. both adjacent elevation bins within a scene (> 5 C)
    df = df.sort_values(["scene", "bin"])
    g = df.groupby("scene")["st"]
    prev, nxt = g.shift(1), g.shift(-1)
    adj = (df["bin"].diff() == BIN_M) & (df["bin"].diff(-1) == -BIN_M)  # true neighbours only
    spike = adj & (((df["st"] - prev > 5) & (df["st"] - nxt > 5)) |
                   ((prev - df["st"] > 5) & (nxt - df["st"] > 5)))
    df = df[~spike]

    # half-month composite (L8 + L9 averaged), per bin
    df["year"], df["hm"] = df["time"].dt.year, _half_month(df["time"])
    comp = (df.groupby(["year", "hm", "bin"])
            .agg(st=("st", "mean"), unc=("unc", "mean"), n=("n", "median")).reset_index())

    # paper filter 3: leave-one-out 3-sigma per (bin, half-month) across years
    grp = comp.groupby(["bin", "hm"])["st"]
    cnt, s, s2 = grp.transform("count"), grp.transform("sum"), grp.transform(lambda x: (x ** 2).sum())
    loo_mean = (s - comp["st"]) / (cnt - 1)
    loo_var = ((s2 - comp["st"] ** 2) / (cnt - 1) - loo_mean ** 2).clip(lower=0)
    out = (cnt >= 6) & ((comp["st"] - loo_mean).abs() > 3 * np.sqrt(loo_var))
    comp = comp[~out]

    # elevation zones with equal glacier area
    area = comp.groupby("bin")["n"].median().sort_index()
    cum_mid = (area.cumsum() - area / 2) / area.sum()
    zone_of_bin = np.minimum((cum_mid * N_ZONES).astype(int), N_ZONES - 1)
    names = {i: f"zone{i + 1}" for i in range(N_ZONES)}
    names[0] += " (low)"
    names[N_ZONES - 1] += " (high)"
    comp["zone"] = comp["bin"].map(zone_of_bin).map(names)
    zone_area = area.groupby(zone_of_bin.map(names)).sum()
    print("\nElevation zones (m a.s.l.):")
    for z, bins in area.groupby(zone_of_bin.map(names)):
        print(f"  {z}: {bins.index.min()}-{bins.index.max() + BIN_M} m, area share {bins.sum() / area.sum():.2f}")

    # area-weighted mean per (year, half-month, zone) and for the whole glacier (Eq. 2)
    # added uncertainty, changed it somehow
    def aw(d):
        m = np.average(d["st"], weights=d["n"])
        sd = np.sqrt(np.average((d["st"] - m) ** 2, weights=d["n"]))
        return pd.Series({"gst": m, "gst_sd": sd,
                          "gst_unc": np.average(d["unc"], weights=d["n"]),
                          "w": d["n"].sum()})

    z = comp.groupby(["year", "hm", "zone"]).apply(aw, include_groups=False).reset_index()
    z = z[z["w"] / z["zone"].map(zone_area) >= MIN_ZONE_COVER]
    a = comp.groupby(["year", "hm"]).apply(aw, include_groups=False).reset_index()
    a = a[a["w"] / area.sum() >= MIN_ZONE_COVER]
    a["zone"] = "whole glacier"
    ts = pd.concat([z, a])
    ts["date"] = pd.to_datetime(dict(year=ts["year"], month=ts["hm"] // 2 + 1,
                                     day=np.where(ts["hm"] % 2 == 0, 8, 23)))

    result = ts.sort_values(["zone", "date"])[["date", "year", "hm", "zone", "gst", "gst_sd", "gst_unc"]]
    return result


def ablation_trend(ts: pd.DataFrame):
    s = ts[ts["hm"].between((ABLATION_MONTHS[0] - 1) * 2, ABLATION_MONTHS[-1] * 2 - 1)]
    yr = (s.groupby(["zone", "year"]).agg(gst=("gst", "mean"), gst_sd=("gst", "std"),
                                          gst_unc=("gst_unc", "mean"), n_hm=("gst", "size")).reset_index())
    yr = yr[yr["n_hm"] >= MIN_HM_PER_SEASON]
    print("\nAblation-season (Jun-Sep) GST trend, deg C per decade:")
    for zone, d in yr.groupby("zone"):
        if len(d) < 4:
            print(f"  {zone}: too few years ({len(d)})")
            continue
        lr = stats.linregress(d["year"], d["gst"])
        ts_slope = stats.theilslopes(d["gst"], d["year"])[0]
        print(f"  {zone}: OLS {lr.slope * 10:+.2f} (p={lr.pvalue:.2f}), "
              f"Theil-Sen {ts_slope * 10:+.2f}, n={len(d)} years")
    return yr


def show_map(dem: ee.Image, roi: ee.Geometry, glacier_mask: ee.Geometry):
    """Optional: quick look in a notebook."""
    m = geemap.Map()
    m.centerObject(roi, 13)
    m.addLayer(dem.clip(roi), {"min": 4500, "max": 6500}, "DEM")
    m.addLayer(glacier_mask.clip(roi), {"palette": "cyan"}, "glacier mask")
    return m


def save_tables_and_figure(raw: pd.DataFrame, time_series: pd.DataFrame, yr: pd.DataFrame, fig: matplotlib.figure.Figure, results_folder: str = ".") -> None:
    raw.to_csv(os.path.join(results_folder, "gst_raw_scene_bins.csv"), index=False)
    time_series.to_csv(os.path.join(results_folder, "gst_halfmonthly.csv"), index=False)
    yr.to_csv(os.path.join(results_folder, "gst_ablation_season.csv"), index=False)
    fig.savefig(os.path.join(results_folder, "gst_series.png"), dpi=300)
    print("\nSaved: gst_raw_scene_bins.csv, gst_halfmonthly.csv, gst_ablation_season.csv, gst_series.png")